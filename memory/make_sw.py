"""Writes sw.js: the offline cache for the web version (GitHub Pages). Run after changing any file:  python3 make_sw.py"""
import hashlib, os
files = ["./", "index.html", "manifest.webmanifest"]
for d in ("assets", "voices", "music", "fonts", "icons"):
    files += sorted(f"{d}/{f}" for f in os.listdir(d) if not f.endswith((".json", ".txt")))
h = hashlib.sha1()
for f in files[1:]: h.update(open(f, "rb").read())
ver = h.hexdigest()[:10]
open("sw.js", "w").write(f"""// Meadow Memory offline cache (generated by make_sw.py - do not edit by hand). Version {ver}
const CACHE = "meadow-memory-{ver}";
const FILES = {files!r};
self.addEventListener("install", e => {{ e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); }});
self.addEventListener("activate", e => {{ e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("meadow-memory-") && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); }});
self.addEventListener("fetch", e => {{
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(r => r || fetch(e.request)));
}});
""")
print("sw.js", ver, len(files), "files")
